# ---------- tokens ----------


def load_tokens():
    return json.loads(TOKENS.read_text(encoding="utf-8"))


def render_tokens_css(tokens):
    color = tokens["color"]
    themes = [theme["id"] for theme in color["themes"]]
    lines = [f"/* {GENERATED_HEADER.format(source='tokens.json')} */", ""]
    for index, theme in enumerate(themes):
        selector = f':root[data-theme="{theme}"]'
        if index == 0:
            selector = f":root,\n{selector}"
        lines.append(f"{selector} {{")
        lines.append(f"  color-scheme: {theme};")
        for token in color["tokens"]:
            lines.append(f"  --{token['name']}: {token['value'][theme]};")
        for token in tokens["shadow"]["tokens"]:
            lines.append(f"  --{token['name']}: {token['value'][theme]};")
        lines.append("}")
        lines.append("")
    lines.append(":root {")
    for name, family in tokens["type"]["families"].items():
        lines.append(f"  --font-{name}: {family};")
    for group in tokens["type"]["groups"]:
        for style in group["styles"]:
            lines.append(
                f"  --font-{style['name']}: {style['fontWeight']} {style['fontSize']}/{style['lineHeight']} var(--font-{group['family']});"
            )
            lines.append(f"  --tracking-{style['name']}: {style.get('letterSpacing', 'normal')};")
    for section in ("spacing", "size", "radius"):
        for token in tokens[section]["tokens"]:
            lines.append(f"  --{token['name']}: {token['value']};")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def render_tokens_js(tokens):
    body = json.dumps(tokens, ensure_ascii=False, indent=2)
    return f"/* {GENERATED_HEADER.format(source='tokens.json')} */\nwindow.KRONELLO_TOKENS = {body};\n"


# ---------- icons ----------


def icon_names_from_doc():
    names = set()
    for line in ICON_DOC.read_text(encoding="utf-8").splitlines():
        if not line.startswith("|") or line.startswith("|---"):
            continue
        cells = line.strip("|").split("|")
        if len(cells) < 2:
            continue
        for name in re.findall(r"`([a-z0-9-]+)`", cells[1]):
            if not name.startswith("kind-") and name != "danger":
                names.add(name)
    return names


SVG_COMMENT = re.compile(r"<!--.*?-->", re.S)


def compact_svg(source):
    svg = SVG_COMMENT.sub("", source).strip()
    svg = re.sub(r"\s*\n\s*", " ", svg)
    svg = re.sub(r"\s+/>", "/>", svg)
    svg = re.sub(r"\s+>", ">", svg)
    return svg


def render_icons_js():
    entries = {}
    for path in sorted(ICON_DIR.glob("*.svg")):
        entries[path.stem] = compact_svg(path.read_text(encoding="utf-8"))
    body = json.dumps(entries, ensure_ascii=False, indent=0, sort_keys=True)
    header = GENERATED_HEADER.format(source="preview/assets/icons/*.svg")
    return f"/* {header} Lucide {LUCIDE['version']}, ISC: see icons/LICENSE. */\nwindow.KRONELLO_ICONS = {body};\n"


# ---------- generated outputs ----------


def generated_outputs():
    tokens = load_tokens()
    return {
        ASSETS / "tokens.css": render_tokens_css(tokens),
        ASSETS / "tokens.js": render_tokens_js(tokens),
        ASSETS / "icons.js": render_icons_js(),
    }


def cmd_render():
    for path, content in generated_outputs().items():
        path.write_text(content, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")


# ---------- check ----------


def preview_sources():
    files = sorted(PREVIEW.rglob("*.html"))
    files += [p for p in sorted(ASSETS.glob("*.js")) if p.name != "icons.js"]
    return files


def used_icons():
    used = {}
    for path in preview_sources():
        for name in re.findall(r'data-icon="([a-z0-9-]+)"', path.read_text(encoding="utf-8")):
            used.setdefault(name, set()).add(path.relative_to(PREVIEW).as_posix())
    return used


def text_characters(paths):
    chars = set()
    for path in paths:
        text = path.read_text(encoding="utf-8")
        if path.suffix == ".html":
            text = html.unescape(text)
        chars.update(ch for ch in text if not ch.isspace())
    return chars


def required_characters():
    return text_characters(preview_sources() + [TOKENS])


def char_ranges(ranges):
    return {chr(code) for start, end in ranges for code in range(start, end + 1)}


def cmd_check():
    errors = []
    for path, expected in generated_outputs().items():
        if not path.exists() or path.read_text(encoding="utf-8") != expected:
            errors.append(f"{path.relative_to(ROOT)} is stale; run `python3 scripts/design_preview.py render`")

    documented = icon_names_from_doc()
    vendored = {p.stem for p in ICON_DIR.glob("*.svg")}
    for name in sorted(documented - vendored):
        errors.append(f"icon `{name}` is listed in icons.md but not vendored; run `vendor-icons`")
    for name in sorted(vendored - documented):
        errors.append(f"icon `{name}` is vendored but not listed in icons.md")
    for name, pages in sorted(used_icons().items()):
        if name not in documented:
            errors.append(f"icon `{name}` used in {', '.join(sorted(pages))} is not listed in icons.md")
    if not (ICON_DIR / "LICENSE").exists():
        errors.append("preview/assets/icons/LICENSE is missing")

    for font in FONTS:
        if not (FONT_DIR / font["output"]).exists():
            errors.append(f"font {font['output']} is missing; run `fonts`")
        if not (FONT_DIR / font["license"]).exists():
            errors.append(f"font license {font['license']} is missing; run `fonts`")
    if SUBSET_LIST.exists():
        covered = set(SUBSET_LIST.read_text(encoding="utf-8"))
        missing = sorted(required_characters() - covered)
        if missing:
            errors.append("characters not covered by the subset fonts (run `fonts`): " + "".join(missing))
    else:
        errors.append("preview/assets/fonts/subset-chars.txt is missing; run `fonts`")

    if errors:
        for error in errors:
            print(f"error: {error}", file=sys.stderr)
        sys.exit(1)
    print(f"design preview OK ({len(vendored)} icons, {len(generated_outputs())} generated files)")


# ---------- downloads ----------


def download(url, sha256, name):
    CACHE.mkdir(parents=True, exist_ok=True)
    destination = CACHE / name
    if destination.exists() and hashlib.sha256(destination.read_bytes()).hexdigest() == sha256:
        return destination.read_bytes()
    if not url.startswith("https://"):
        fail(f"refusing non-HTTPS download: {url}")
    request = urllib.request.Request(url, headers={"User-Agent": "kronello-design-preview/1"})
    with urllib.request.urlopen(request, timeout=120) as response:
        data = response.read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != sha256:
        fail(f"SHA-256 mismatch for {url}: {digest}")
    destination.write_bytes(data)
    return data


def cmd_vendor_icons():
    data = download(LUCIDE["url"], LUCIDE["sha256"], f"lucide-static-{LUCIDE['version']}.tgz")
    names = icon_names_from_doc()
    with tarfile.open(fileobj=io.BytesIO(data), mode="r:gz") as archive:
        package = json.load(archive.extractfile("package/package.json"))
        if package["version"] != LUCIDE["version"]:
            fail(f"unexpected lucide-static version {package['version']}")
        members = {m.name: m for m in archive.getmembers()}
        missing = [n for n in sorted(names) if f"package/icons/{n}.svg" not in members]
        if missing:
            fail("icons not found in lucide-static: " + ", ".join(missing))
        if ICON_DIR.exists():
            shutil.rmtree(ICON_DIR)
        ICON_DIR.mkdir(parents=True)
        for name in sorted(names):
            (ICON_DIR / f"{name}.svg").write_bytes(archive.extractfile(f"package/icons/{name}.svg").read())
        (ICON_DIR / "LICENSE").write_bytes(archive.extractfile("package/LICENSE").read())
    print(f"vendored {len(names)} icons from lucide-static {LUCIDE['version']}")
    cmd_render()


def cmd_fonts():
    pyftsubset = shutil.which("pyftsubset")
    if not pyftsubset:
        fail("pyftsubset not found; install fontTools with brotli (pip install 'fonttools[woff]')")
    FONT_DIR.mkdir(parents=True, exist_ok=True)
    text_chars = required_characters() | char_ranges(BASE_RANGES)
    base = f"https://raw.githubusercontent.com/google/fonts/{GOOGLE_FONTS_COMMIT}/"
    for font in FONTS:
        data = download(base + font["path"], font["sha256"], Path(font["path"]).name.replace("%5B", "[").replace("%5D", "]"))
        license_text = urllib.request.urlopen(base + font["license_path"], timeout=60).read()
        (FONT_DIR / font["license"]).write_bytes(license_text)
        chars = text_chars if font["coverage"] == "text" else char_ranges(MONO_RANGES)
        with tempfile.TemporaryDirectory() as tmp:
            source = Path(tmp) / "source.ttf"
            source.write_bytes(data)
            text_file = Path(tmp) / "chars.txt"
            text_file.write_text("".join(sorted(chars)), encoding="utf-8")
            subprocess.run(
                [
                    pyftsubset, str(source), f"--text-file={text_file}", "--flavor=woff2",
                    "--layout-features=*", "--no-hinting", "--desubroutinize",
                    f"--output-file={FONT_DIR / font['output']}",
                ],
                check=True,
            )
        print(f"wrote {(FONT_DIR / font['output']).relative_to(ROOT)} ({(FONT_DIR / font['output']).stat().st_size} bytes)")
    covered = font_coverage(pyftsubset, [FONT_DIR / font["output"] for font in FONTS])
    missing = sorted(required_characters() - covered)
    if missing:
        fail("characters not in Noto Sans JP / Noto Sans Mono; replace them in the preview: " + "".join(missing))
    SUBSET_LIST.write_text("".join(sorted(ch for ch in covered if not ch.isspace())) + "\n", encoding="utf-8")
    print(f"wrote {SUBSET_LIST.relative_to(ROOT)} ({len(covered)} characters)")


def font_coverage(pyftsubset, paths):
    """Read the cmap of the subset fonts with the Python that runs pyftsubset (it has fontTools)."""
    first_line = Path(pyftsubset).read_text(encoding="utf-8", errors="replace").splitlines()[0]
    python = first_line[2:].strip() if first_line.startswith("#!") else sys.executable
    script = (
        "import sys\nfrom fontTools.ttLib import TTFont\ncodes=set()\n"
        "for path in sys.argv[1:]:\n    codes.update(TTFont(path).getBestCmap())\n"
        "print(' '.join(map(str, sorted(codes))))\n"
    )
    output = subprocess.run([*python.split(), "-c", script, *map(str, paths)], check=True, capture_output=True, text=True).stdout
    return {chr(int(code)) for code in output.split()}


