#!/usr/bin/env python3
"""Build and verify the visual preview of the GUI design system.

The preview lives in docs/design-system/preview/. Its HTML pages render the
components and screens from docs/design-system/ with values generated from
tokens.json, so they can be opened from file:// and screenshotted again.

Usage:
    python3 scripts/design_preview.py render        # regenerate tokens.css, tokens.js, icons.js
    python3 scripts/design_preview.py check         # verify generated files, icons and font coverage
    python3 scripts/design_preview.py vendor-icons  # copy the icons listed in icons.md from pinned lucide-static
    python3 scripts/design_preview.py fonts         # subset pinned Noto fonts (needs pyftsubset + brotli)
    python3 scripts/design_preview.py screenshots   # render images/ with headless Chrome

`check` and `render` use only the standard library. `fonts` needs fontTools
(pyftsubset) with brotli; `screenshots` needs Google Chrome or Chromium
(override the binary with the CHROME environment variable).
"""

