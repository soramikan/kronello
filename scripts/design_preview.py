def chrome_binary():
    candidates = [os.environ.get("CHROME")] if os.environ.get("CHROME") else []
    candidates += [
        "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
        "/Applications/Chromium.app/Contents/MacOS/Chromium",
        shutil.which("google-chrome"), shutil.which("chromium"), shutil.which("chromium-browser"),
    ]
    for candidate in candidates:
        if candidate and Path(candidate).exists():
            return candidate
    fail("Chrome not found; set CHROME to a Chrome or Chromium binary")


CHROME_FLAGS = [
    "--headless", "--disable-gpu", "--hide-scrollbars", "--no-first-run", "--no-default-browser-check",
    "--disable-background-networking", "--disable-sync", "--disable-extensions", "--mute-audio",
    "--force-color-profile=srgb", "--font-render-hinting=none", "--allow-file-access-from-files",
]


class Chrome:
    """Minimal Chrome DevTools Protocol client over --remote-debugging-pipe (standard library only)."""

    def __init__(self, binary, profile):
        to_chrome_r, self._to_chrome = os.pipe()
        self._from_chrome, from_chrome_w = os.pipe()

        def wire_pipes():
            # Chrome reads commands from fd 3 and writes replies to fd 4.
            read_end, write_end = os.dup(to_chrome_r), os.dup(from_chrome_w)
            os.dup2(read_end, 3)
            os.dup2(write_end, 4)

        self._process = subprocess.Popen(
            [binary, *CHROME_FLAGS, "--remote-debugging-pipe", f"--user-data-dir={profile}", "about:blank"],
            pass_fds=(3, 4), preexec_fn=wire_pipes,
            stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
        )
        os.close(to_chrome_r)
        os.close(from_chrome_w)
        self._buffer = b""
        self._next_id = 0
        self._events = []
        targets = self.call("Target.getTargets")["targetInfos"]
        page = next(t for t in targets if t["type"] == "page")
        self._session = self.call("Target.attachToTarget", targetId=page["targetId"], flatten=True)["sessionId"]
        self.call("Page.enable", session=True)

    def _read_message(self, deadline):
        while b"\0" not in self._buffer:
            if time.monotonic() > deadline:
                fail("timed out waiting for Chrome")
            chunk = os.read(self._from_chrome, 1 << 20)
            if not chunk:
                fail("Chrome closed the DevTools pipe")
            self._buffer += chunk
        message, self._buffer = self._buffer.split(b"\0", 1)
        return json.loads(message)

    def call(self, method, session=False, timeout=60, **params):
        self._next_id += 1
        message = {"id": self._next_id, "method": method, "params": params}
        if session:
            message["sessionId"] = self._session
        os.write(self._to_chrome, json.dumps(message).encode() + b"\0")
        deadline = time.monotonic() + timeout
        while True:
            reply = self._read_message(deadline)
            if reply.get("id") == self._next_id:
                if "error" in reply:
                    fail(f"{method}: {reply['error'].get('message')}")
                return reply.get("result", {})
            self._events.append(reply)

    def wait_event(self, method, timeout=60):
        deadline = time.monotonic() + timeout
        while True:
            for index, event in enumerate(self._events):
                if event.get("method") == method:
                    return self._events.pop(index)
            self._events.append(self._read_message(deadline))

    def evaluate(self, expression):
        result = self.call("Runtime.evaluate", session=True, expression=expression, awaitPromise=True, returnByValue=True)
        if "exceptionDetails" in result:
            fail(f"page script failed: {result['exceptionDetails'].get('text')}")
        return result["result"].get("value")

    def close(self):
        try:
            self.call("Browser.close", timeout=10)
        except SystemExit:
            pass
        try:
            self._process.wait(timeout=10)
        except subprocess.TimeoutExpired:
            self._process.kill()
        os.close(self._to_chrome)
        os.close(self._from_chrome)


READY = """new Promise(resolve => {
  const poll = () => document.documentElement.dataset.ready
    ? requestAnimationFrame(() => requestAnimationFrame(() => resolve({
        width: Number(document.documentElement.dataset.width),
        height: Number(document.documentElement.dataset.height),
        errors: document.querySelectorAll('i[data-icon]').length })))
    : setTimeout(poll, 50);
  poll();
})"""


def shoot(chrome, page, query, output, size=None, width=None):
    url = (PREVIEW / page).as_uri() + "?" + "&".join(filter(None, [query, "capture"]))
    viewport = size or (width, 900)
    chrome.call("Emulation.setDeviceMetricsOverride", session=True, width=viewport[0], height=viewport[1],
                deviceScaleFactor=SCALE, mobile=False)
    chrome.call("Page.navigate", session=True, url=url)
    chrome.wait_event("Page.loadEventFired")
    state = chrome.evaluate(READY)
    if state["errors"]:
        fail(f"{page}?{query}: {state['errors']} icon(s) failed to render")
    if size is None:
        size = (max(width, state["width"]), state["height"])
        chrome.call("Emulation.setDeviceMetricsOverride", session=True, width=size[0], height=size[1],
                    deviceScaleFactor=SCALE, mobile=False)
        chrome.evaluate("new Promise(r => requestAnimationFrame(() => requestAnimationFrame(r)))")
    shot = chrome.call("Page.captureScreenshot", session=True, format="png", fromSurface=True)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_bytes(base64.b64decode(shot["data"]))
    print(f"wrote {output.relative_to(ROOT)} ({size[0]}×{size[1]} @{SCALE}x)")


def section_ids(page):
    source = (PREVIEW / page).read_text(encoding="utf-8")
    return re.findall(r'<section[^>]*data-section[^>]*id="([A-Za-z]+)"', source)


def screenshot_jobs():
    """Yield (group, name, page, query, output, size, width) for every image."""
    # Foundations show both themes side by side where it matters, so they are captured in Dark only.
    for section in section_ids("index.html"):
        yield ("foundations", section, "index.html", f"only={section}&theme=dark",
               IMAGES / "foundations" / f"{section}.png", None, FOUNDATIONS_WIDTH)
    for component in section_ids("components.html"):
        for theme in THEMES:
            yield ("components", component, "components.html", f"only={component}&theme={theme}",
                   IMAGES / "components" / f"{component}-{theme}.png", None, COMPONENT_WIDTH)
    for name, page, query, themes in SCREENS:
        for theme in themes:
            yield ("screens", name, page, "&".join(filter(None, [query, f"theme={theme}"])),
                   IMAGES / "screens" / f"{name}-{theme}.png", SCREEN_SIZE, None)


def cmd_screenshots(selected):
    """Render all images, or only the groups / names given (e.g. `screens`, `motion`, `Button`)."""
    jobs = [job for job in screenshot_jobs() if not selected or job[0] in selected or job[1] in selected]
    if not jobs:
        fail("nothing matches: " + " ".join(sorted(selected)))
    binary = chrome_binary()
    with tempfile.TemporaryDirectory() as profile:
        chrome = Chrome(binary, profile)
        try:
            for _group, _name, page, query, output, size, width in jobs:
                shoot(chrome, page, query, output, size=size, width=width)
        finally:
            chrome.close()
    if not selected:
        expected = {job[4] for job in jobs}
        for stale in sorted(set(IMAGES.rglob("*.png")) - expected):
            stale.unlink()
            print(f"removed {stale.relative_to(ROOT)}")


def main():
    if len(sys.argv) < 2:
        fail(__doc__.strip().splitlines()[0] + " — see --help")
    command, rest = sys.argv[1], sys.argv[2:]
    if command in ("-h", "--help"):
        print(__doc__)
    elif command == "render":
        cmd_render()
    elif command == "check":
        cmd_check()
    elif command == "vendor-icons":
        cmd_vendor_icons()
    elif command == "fonts":
        cmd_fonts()
    elif command == "screenshots":
        cmd_screenshots(set(rest))
    else:
        fail(f"unknown command: {command}")


if __name__ == "__main__":
    main()
